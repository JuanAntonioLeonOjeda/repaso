"""Writes the data module of SamplingSim: the 30 most likely next tokens (and their logits) that
the tutorial's GPT gives after a prompt, from the results.json written by llm.py.

    python scripts/tutorials/llm_next_token.py /path/to/out/results.json \
        > src/features/simulations/tutorials/llm-next-token.ts
"""

import json
import sys


def main() -> None:
    nt = json.loads(open(sys.argv[1], encoding="utf-8").read())["generate"]["next_token"]
    print("// Generated by scripts/tutorials/llm_next_token.py from a run of scripts/tutorials/llm.py.")
    print("export const nextToken = {")
    print(f"  prompt: {json.dumps(nt['prompt'], ensure_ascii=False)},")
    print(f"  tokens: {json.dumps(nt['tokens'], ensure_ascii=False)},")
    print(f"  logits: {json.dumps(nt['logits'])},")
    print("} as const;")


if __name__ == "__main__":
    main()
