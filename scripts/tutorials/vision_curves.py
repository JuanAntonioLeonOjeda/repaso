"""Turns the training histories in the results.json written by vision.py into the data module of
TrainingCurvesSim (only aggregate per-epoch metrics).

    python scripts/tutorials/vision_curves.py /path/to/out/results.json \
        > src/features/simulations/tutorials/vision-runs.ts
"""

import json
import sys

RUNS = [
    ("mlp", "MLP", ["mlp"]),
    ("cnn", "CNN", ["cnn"]),
    ("cnn_reg", "CNN regularizada", ["cnn_reg"]),
    ("resnet", "ResNet-18 (2 fases)", ["transfer.feature_extraction", "transfer.fine_tuning"]),
]


def history(results: dict, path: str) -> list[dict]:
    node = results
    for part in path.split("."):
        node = node[part]
    return node["history"]


def main() -> None:
    results = json.loads(open(sys.argv[1]).read())
    print("// Generated by scripts/tutorials/vision_curves.py from a run of scripts/tutorials/vision.py.")
    print('import type { TrainingRun } from "./training-curves";\n')
    print("export const visionRuns: readonly TrainingRun[] = [")
    for key, label, paths in RUNS:
        epochs = [h for p in paths for h in history(results, p)]
        print(f'  {{\n    key: "{key}",\n    label: "{label}",\n    epochs: [')
        for i, h in enumerate(epochs, start=1):
            t, v = h["train"], h["val"]
            print(
                f"      {{ epoch: {i}, trainLoss: {t['loss']:.4f}, trainAcc: {t['acc']:.4f}, "
                f"valLoss: {v['loss']:.4f}, valAcc: {v['acc']:.4f} }},"
            )
        print("    ],\n  },")
    print("];")


if __name__ == "__main__":
    main()
